<?php
declare(strict_types=1);

use ParagonIE\ConstantTime\Hex;
use ParagonIE\Halite\Alerts\{
    CannotPerformOperation,
    FileAccessDenied,
    FileError,
    FileModified,
    InvalidDigestLength,
    InvalidKey,
    InvalidMessage,
    InvalidSignature,
    InvalidType
};
use ParagonIE\Halite\Asymmetric\EncryptionSecretKey;
use ParagonIE\Halite\{
    File,
    Halite,
    KeyFactory,
    Symmetric\Crypto,
    Symmetric\EncryptionKey,
};
use ParagonIE\HiddenString\HiddenString;
use PHPUnit\Framework\TestCase;

final class VersionMigrationTest extends TestCase
{
    /**
     * @throws CannotPerformOperation
     * @throws InvalidDigestLength
     * @throws InvalidKey
     * @throws InvalidMessage
     * @throws InvalidSignature
     * @throws InvalidType
     * @throws SodiumException
     */
    public function testDefaultWriteVersions(): void
    {
        $key = new EncryptionKey(new HiddenString(str_repeat('A', 32)));
        $ciphertext = Crypto::encryptWithAD(
            new HiddenString('migration test'),
            $key,
            'migration aad',
            true
        );
        $this->assertSame("\x31\x42\x05\x00", substr($ciphertext, 0, 4));
        $this->assertSame(
            'migration test',
            Crypto::decryptWithAD($ciphertext, $key, 'migration aad', true)
                ->getString()
        );
        $this->assertSame('31400500', substr(KeyFactory::export($key)->getString(), 0, 8));

        $this->assertSame("\x31\x41\x05\x00", Halite::HALITE_VERSION_FILE);
    }

    /**
     * @throws CannotPerformOperation
     * @throws FileAccessDenied
     * @throws FileError
     * @throws FileModified
     * @throws InvalidDigestLength
     * @throws InvalidKey
     * @throws InvalidMessage
     * @throws InvalidType
     * @throws SodiumException
     */
    public function testDefaultFileWriteVersions(): void
    {
        $input = tempnam(sys_get_temp_dir(), 'halite-input-');
        $output = tempnam(sys_get_temp_dir(), 'halite-output-');
        $plain = tempnam(sys_get_temp_dir(), 'halite-plain-');
        file_put_contents($input, 'migration test');
        $key = new EncryptionKey(new HiddenString(str_repeat('A', 32)));
        $secret = new EncryptionSecretKey(new HiddenString(str_repeat('B', 32)));
        try {
            File::encrypt($input, $output, $key);
            $this->assertSame(
                "\x31\x41\x05\x00",
                file_get_contents($output, false, null, 0, 4)
            );
            File::decrypt($output, $plain, $key);
            $this->assertSame('migration test', file_get_contents($plain));

            File::seal($input, $output, $secret->derivePublicKey());
            $this->assertSame(
                "\x31\x41\x05\x00",
                file_get_contents($output, false, null, 0, 4)
            );
            File::unseal($output, $plain, $secret);
            $this->assertSame('migration test', file_get_contents($plain));
        } finally {
            unlink($input);
            unlink($output);
            unlink($plain);
        }
    }

    /**
     * @throws CannotPerformOperation
     * @throws FileAccessDenied
     * @throws FileError
     * @throws FileModified
     * @throws InvalidDigestLength
     * @throws InvalidKey
     * @throws InvalidMessage
     * @throws InvalidType
     * @throws SodiumException
     */
    public function testReadVersion515SealedFile(): void
    {
        $input = tempnam(sys_get_temp_dir(), 'halite-sealed-');
        $output = tempnam(sys_get_temp_dir(), 'halite-plain-');
        // Generated by 5.1.5 using a secret key of 32 B bytes and AAD "migration aad".
        $ciphertext = 'MUEFAYz5YBJb7J5gPSCg+rmCYF7e5hLeQxXJLBdiz/9qIz40kUw7JK/Wr3rMD3f9dWmhbCtoNEDjsNvfzgJ/rOzjQGqBXq6PwZfg4CHvnBHHY1zQ3ABl0zuTkoDgpNaCcAgkfrLrVXlTON5p9D6lJWns';
        file_put_contents($input, base64_decode($ciphertext));
        $secret = new EncryptionSecretKey(new HiddenString(str_repeat('B', 32)));
        try {
            try {
                File::unseal($input, $output, $secret, 'migration bad');
                $this->fail('Modified AAD was accepted');
            } catch (\ParagonIE\Halite\Alerts\InvalidMessage $ex) {
                $this->assertSame('Invalid message authentication code', $ex->getMessage());
            }
            File::unseal($input, $output, $secret, 'migration aad');
            $this->assertSame('migration test', file_get_contents($output));
        } finally {
            unlink($input);
            unlink($output);
        }
    }

    /**
     * @throws CannotPerformOperation
     * @throws InvalidDigestLength
     * @throws InvalidKey
     * @throws InvalidMessage
     * @throws InvalidSignature
     * @throws InvalidType
     * @throws SodiumException
     */
    public function testReadVersion515Ciphertext(): void
    {
        // Generated with Halite 5.1.5, before restoring the default write version.
        $ciphertext = 'MUIFAe0r8tL0atTQQb6N3MOqKf3K4HGEQLHl4HwbN3QsJnqODIefO-D_lt7u9LOmovAX_4P-eA_L2jhAOTD21wKBlZ5izc1Nzxp_Ophu4wq-OlKNuzDdAmQgIEjG1aUxkaeQWWg_vOSZhRBXouqYUUsHWXrAXyeQxRzkcTY2bY-dHtGruxxgFoGw';
        $key = new EncryptionKey(new HiddenString(str_repeat('A', 32)));
        $this->assertSame(
            'migration test',
            Crypto::decryptWithAD($ciphertext, $key, 'migration aad')
                ->getString()
        );
    }

    /**
     * @throws CannotPerformOperation
     * @throws InvalidDigestLength
     * @throws InvalidKey
     * @throws InvalidMessage
     * @throws InvalidSignature
     * @throws InvalidType
     * @throws SodiumException
     */
    public function testReadVersion514Ciphertext(): void
    {
        // Generated independently using the v5.1.4 source tree.
        $ciphertext = 'MUIFAB4TXM4eRJIlWfxQXXmN4hwbh0qns7XtQ5YjtuZgtra_yuRS2eSKk8CHpat89x_qMk9CWDHeXwfoNib8i2YerPPngWKCM_QDzcHxq6eNZkR5ehCjV56s1mo7Nsu5XntzLOLnaXkv7cUAIRfF2htKlJhMuYD6jzn8A7OIUkfWFMPEljTuzi9h';
        $key = new EncryptionKey(
            new HiddenString(str_repeat('A', 32))
        );
        $this->assertSame(
            'migration test',
            Crypto::decryptWithAD($ciphertext, $key, 'migration aad')
                ->getString()
        );
    }

    /**
     * @throws InvalidKey
     * @throws SodiumException
     */
    public function testReadBothKeyVersions(): void
    {
        $keyMaterial = str_repeat('A', 32);
        foreach (["\x31\x40\x05\x00", "\x31\x40\x05\x01"] as $header) {
            $data = $header . $keyMaterial;
            $encoded = Hex::encode($data . sodium_crypto_generichash($data, '', 64));
            $key = KeyFactory::importEncryptionKey(new HiddenString($encoded));
            $this->assertSame($keyMaterial, $key->getRawKeyMaterial());
        }
    }
}
